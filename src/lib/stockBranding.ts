/** Normalizes symbol or resolves by company name if ticker is incomplete. */
export function resolveTickerSymbol(symbol?: string | null, name?: string | null): string {
  const sym = (symbol || "").trim().toUpperCase();
  const n = (name || "").toLowerCase();

  if (sym === "SCOM" || sym === "SAFA" || sym.startsWith("SAFARI") || n.includes("safaricom")) {
    return "SCOM";
  }
  if (sym === "SGL" || sym.startsWith("STAND") || n.includes("standard group")) {
    return "SGL";
  }
  if (sym === "CTUM" || sym.startsWith("CENT") || n.includes("centum")) {
    return "CTUM";
  }
  if (sym === "KEGN" || sym.startsWith("KENG") || n.includes("kengen")) {
    return "KEGN";
  }
  if (sym === "LKL" || sym.startsWith("LONG") || n.includes("longhorn")) {
    return "LKL";
  }
  if (sym === "UMME" || sym.startsWith("UMEM") || n.includes("umeme")) {
    return "UMME";
  }
  if (sym === "KQ" || n.includes("kenya airways")) {
    return "KQ";
  }
  return sym;
}

/**
 * Resolves a stock ticker to an official logo URL.
 * Prefers the provided logoUrl if present. Falls back to bundled local artwork
 * or reviewed hosted storage artwork.
 */
export function getStockLogoUrl(symbol: string, logoUrl?: string | null, name?: string | null) {
  if (logoUrl?.trim()) return logoUrl;
  const canonical = resolveTickerSymbol(symbol, name);
  return BUNDLED_STOCK_LOGOS[canonical] || HOSTED_STOCK_LOGOS[canonical] || "";
}

/** Returns the local bundled logo URL if available for this stock ticker. */
export function getBundledStockLogoUrl(symbol: string, name?: string | null) {
  const canonical = resolveTickerSymbol(symbol, name);
  return BUNDLED_STOCK_LOGOS[canonical] || "";
}
